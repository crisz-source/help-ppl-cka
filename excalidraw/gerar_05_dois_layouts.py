CINZA = "#495057"

# =============================================================== DIAGRAMA (edite daqui)
text(60, 30, "Um conteúdo, dois sites", size=36)
text(60, 85, "Você escreve uma vez em docs/; o CI gera o site clássico e o interativo a partir do mesmo texto.", size=20, color=CINZA)

text(60, 160, "1. QUEM ESCREVE", size=22, color=AMARELO)
fonte = box(60, 330, 320, 160, "docs/*.md\na fonte única\nO texto de todas as páginas.\nO nav do mkdocs.yml\nvira o menu dos dois", fill=AMARELO_F, stroke=AMARELO)

text(460, 160, "2. QUEM MONTA (no CI, a cada push)", size=22, color=AZUL)
frame(460, 200, 460, 470, "", AZUL_F, AZUL)
mk = box(490, 230, 400, 110, "MkDocs Material\no gráfico clássico\nMonta o layout de sempre", fill="#ffffff", stroke=AZUL)
sync = box(490, 390, 400, 110, "sync-docs — o tradutor\nAdapta avisos, soluções\ne diagramas para o Astro", fill="#ffffff", stroke=AZUL)
astro = box(490, 540, 400, 110, "Astro Starlight\no gráfico interativo\nTerminal animado e progresso", fill="#ffffff", stroke=AZUL)

text(1000, 160, "3. QUEM LÊ", size=22, color=VERDE)
s1 = box(1000, 230, 360, 110, "Site clássico\n/help-ppl-cka/", fill=VERDE_F, stroke=VERDE)
s2 = box(1000, 540, 360, 110, "Site interativo\n/help-ppl-cka/v2/", fill=VERDE_F, stroke=VERDE)

arrow(fonte, mk, color=AMARELO)
arrow(fonte, sync, color=AMARELO)
arrow(sync, astro, color=AZUL)
